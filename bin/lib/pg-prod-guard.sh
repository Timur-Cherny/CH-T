#!/usr/bin/env bash
# Общие проверки прод-обёрток MCP-сервера Postgres.
#
# ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Проверок три, и все три — свойства канала, а не
# конкретного контура: сервер не деградировал, адреса взяты из файла вне git,
# туннель поднят. Второй прод-контур (django-core) означал бы вторую копию тех
# же тридцати строк — а расходятся копии молча: INC-PG-READONLY-BYPASS ровно так
# и жил, объявив маркерную проверку своим regression_guard за месяц до того, как
# она появилась. Здесь она одна на всех, и тест перебирает обёртки списком.
#
# Каждая функция первым аргументом берёт имя обёртки — оно уходит в stderr, и по
# нему видно, какой именно канал отказал.

# Три защиты read-only держат Postgres и протокол, а не разбор строки запроса;
# здесь проверяется только, что они физически на месте в коде сервера.
# Закомментированная строка защитой не считается.
pg_guard_entry() {
  local tag="$1" entry="$2" marker what
  [ -r "$entry" ] || { echo "$tag: нет пинованного сервера ($entry)" >&2; return 1; }
  while IFS='|' read -r marker what; do
    grep -v -E '^[[:space:]]*//' "$entry" | grep -qF "$marker" || {
      echo "$tag: в сервере нет защиты «$what» — старт отменён ($entry)" >&2; return 1; }
  done <<'MARKERS'
BEGIN TRANSACTION READ ONLY|замок режима транзакции
current_setting('transaction_read_only')|пост-проверка режима после запроса
name: `ro_|расширенный протокол (именованный statement)
MARKERS
}

# Канал, объявленный читающим с реплики, обязан получить сервер, который это
# проверяет: иначе PG_RO_REQUIRE_STANDBY=1 — просто переменная, а чтение молча
# уходит на мастер. Проверяется наличие обеих половин защиты в коде сервера.
pg_guard_standby() {
  local tag="$1" entry="$2" marker what
  while IFS='|' read -r marker what; do
    grep -v -E '^[[:space:]]*//' "$entry" | grep -qF "$marker" || {
      echo "$tag: в сервере нет защиты «$what» — старт отменён ($entry)" >&2; return 1; }
  done <<'MARKERS'
PG_RO_REQUIRE_STANDBY|переключатель обязательной реплики
pg_is_in_recovery()|проверка, что инстанс — реплика
MARKERS
}

# Адреса контуров живут вне git (решение 14.08: карта инфраструктуры опаснее пароля).
# Источник читается ПОСЛЕ разбора окружения сессии и перекрывает его: подменить
# контур, выставив PG_*_DB перед запуском обёртки, нельзя.
pg_guard_infra() {
  local tag="$1"; shift
  local infra="$HOME/.claude/env/mcp-infra.sh" v
  [ -r "$infra" ] || { echo "$tag: нет $infra — адреса контуров живут вне git" >&2; return 1; }
  . "$infra"
  for v in "$@"; do
    [ -n "${!v:-}" ] || { echo "$tag: в $infra нет $v" >&2; return 1; }
  done
}

# Пароль берёт pg из ~/.pgpass: в строке подключения его нет, аргументы процесса
# видны в `ps` любому локальному процессу.
pg_guard_pgpass() {
  local tag="$1"
  [ -r "$HOME/.pgpass" ] || { echo "$tag: нет ~/.pgpass — пароль взять негде" >&2; return 1; }
}

# Сеть проверяем до старта: без VPN сервер поднялся бы и падал на каждом запросе
# таймаутом, а причину искали бы в сервере, а не в туннеле.
pg_guard_net() {
  local tag="$1" host="$2" port="$3"
  nc -z -G 3 "$host" "$port" 2>/dev/null || {
    echo "$tag: $host:$port недоступен — поднят ли OpenVPN (профиль контура)?" >&2; return 1; }
}
